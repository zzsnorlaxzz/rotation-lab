import assert from 'node:assert/strict';
import {dragTarget,draggedAngle} from '../src/interaction.ts';
const dots=[{x:100,y:100},{x:250,y:140}];
assert.equal(dragTarget(1,{x:110,y:105},dots),'view');
assert.equal(dragTarget(2,{x:250,y:140},dots),'view');
assert.equal(dragTarget(1,{x:170,y:170},dots),'view');
assert.equal(dragTarget(2,{x:170,y:170},dots),'view');
assert.equal(dragTarget(3,{x:100,y:100},dots),'view');
assert.equal(dragTarget(1,{x:100,y:100},[]),'view');
assert.equal(draggedAngle(90,150),180);
assert.equal(draggedAngle(180,-150),90);
assert.equal(draggedAngle(0,-100),0);
assert.equal(draggedAngle(360,100),360);
assert.equal(dragTarget(1,{x:170,y:170},dots,true),'view');
assert.equal(dragTarget(3,{x:170,y:170},dots,true),'view');
assert.equal(dragTarget(1,{x:130,y:100},dots),'view');
assert.equal(draggedAngle(0,210,300),360);
assert.equal(draggedAngle(0,420,600),360);
assert.ok(draggedAngle(360,-1,300)<360);
assert.ok(draggedAngle(0,1,300)>0);
console.log('✓ 모든 3D 드래그는 시점 변경, 별도 회전 바의 되감기 및 각도 제한 검사 통과');
